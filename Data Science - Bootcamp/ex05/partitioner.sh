#!/bin/sh

# Скрипт partitioner.sh

# Проверяем, что входной файл указан
if [ "$#" -ne 1 ]; then
  echo "Использование: $0 <входной_csv_файл>"
  exit 1
fi

INPUT_FILE=$1

# Проверяем, существует ли файл
if [ ! -f "$INPUT_FILE" ]; then
  echo "Ошибка: Файл $INPUT_FILE не существует."
  exit 1
fi

# Считываем заголовок файла
HEADER=$(head -n 1 "$INPUT_FILE")

# Разбиваем строки на файлы по полной дате (год-месяц-день)
awk -F',' -v header="$HEADER" '
NR == 1 { next }  # Пропускаем заголовок
{
  # Убираем кавычки вокруг второго столбца
  gsub(/"/, "", $2);
  
  # Извлекаем дату (первые 10 символов)
  date = substr($2, 1, 10);
  
  # Проверяем формат даты
  if (date ~ /^[0-9]{4}-[0-9]{2}-[0-9]{2}$/) {
    file = date ".csv";  # Имя выходного файла
    if (!(file in seen)) {
      print header > file;  # Добавляем заголовок в файл
      seen[file] = 1;
    }
    print $0 >> file;  # Добавляем строку в файл
  } else {
    print "Ошибка в строке: \"" $0 "\" - некорректный формат даты" > "/dev/stderr";
  }
}' "$INPUT_FILE"

# Сообщение об успешном завершении
echo "Разбиение завершено. Проверьте созданные файлы в формате YYYY-MM-DD.csv."
